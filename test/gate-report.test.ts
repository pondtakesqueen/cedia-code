import { describe, expect, test } from "bun:test";
import { gatedFiles, gateSection, judge } from "../evals/gate-report.ts";

const template = (gate: string) =>
  `## What and why\n\nx\n\n## Verify\n\ny\n\n## Risk\n\nlow\n\n## Eval gate\n\n<!-- For a change to a prompt ... Otherwise: not needed. -->\n${gate}\n\n---\n_Generated by Claude Code_\n`;

describe("gate report check", () => {
  test("which files the gate covers", () => {
    expect(gatedFiles([
      "src/core/loop/run.ts", "src/core/prompts.ts", "src/core/run/thread.ts", "src/clients/headless/main.ts", "evals/run.ts", "evals/tasks/x/task.json", "bun.lock",
      "src/clients/tui-ink/app.tsx", "docs/CLI.md", "test/loop.test.ts", "evals/gate-report.ts", "evals/gate/README.md", "src/core/lsp/client.ts",
    ])).toEqual(["src/core/loop/run.ts", "src/core/prompts.ts", "src/core/run/thread.ts", "src/clients/headless/main.ts", "evals/run.ts", "evals/tasks/x/task.json", "bun.lock"]);
  });

  test("a PR that touches no gated file passes without a section", () => {
    expect(judge(["src/clients/tui-ink/app.tsx", "docs/CLI.md"], "no sections")).toMatchObject({ ok: true, kind: "not-gated" });
  });

  test("the section ends at the next heading or rule, and the template's hint is not text", () => {
    expect(gateSection(template("Not run yet."))).toBe("Not run yet.");
    expect(gateSection(template(""))).toBe("");
    expect(gateSection("## What\n\nx")).toBeNull();
  });

  test("a pasted gate report passes", () => {
    const report = "```\nSpent $0.2551\n\nopencode-go/claude-haiku-5-5: PASS\n  pass@1  48/48 -> 48/48  ok\n```";
    expect(judge(["src/core/loop/run.ts"], template(report))).toMatchObject({ ok: true, kind: "report" });
    expect(judge(["src/core/loop/run.ts"], template("Rows: `evals/results/2026-11-05-gate-opencode-go_claude-haiku-5-5-abc1234-101010.jsonl`"))).toMatchObject({ ok: true, kind: "report" });
  });

  test("not needed passes only with a reason", () => {
    expect(judge(["src/cli.ts"], template("Not needed. Nothing on the default path changed, and the gate suite runs without --jobs."))).toMatchObject({ ok: true, kind: "not-needed" });
    expect(judge(["src/cli.ts"], template("Not needed."))).toMatchObject({ ok: false, kind: "no-report" });
  });

  // The bodies of #234 and #236, which merged without a gate run.
  test("a section that says the gate was not run fails", () => {
    expect(judge(["src/clients/headless/main.ts"], template("Not run yet. `bun evals/gate.ts --estimate`, then `bun evals/gate.ts`, is needed before merging."))).toMatchObject({ ok: false, kind: "no-report" });
    expect(judge(["src/core/loop/profile.ts"], template("Not run. `bun evals/gate.ts --estimate` fails in this clone because the gate needs full git history, and it spends money. Please run it before merging."))).toMatchObject({ ok: false, kind: "no-report" });
  });

  test("a gated PR with no section fails and names the files", () => {
    const v = judge(["src/core/tools/bash.ts"], "## What and why\n\nx");
    expect(v).toMatchObject({ ok: false, kind: "missing-section" });
    expect(v.message).toContain("src/core/tools/bash.ts");
  });
});
